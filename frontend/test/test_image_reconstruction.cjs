const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs'), os = require('node:os');
const { execFileSync } = require('node:child_process');
const { harness } = require('./browser_helpers.cjs');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'sisa-image-fixture-'));
const fixture = process.env.SISA_RECONSTRUCTION_FIXTURE || path.join(directory, 'pouch.png');
if (!process.env.SISA_RECONSTRUCTION_FIXTURE) execFileSync('python', ['-c', 'import sys; from pathlib import Path; from backend.tests.test_image_model import illustration; Path(sys.argv[1]).write_bytes(illustration())', fixture], { cwd: path.resolve(__dirname, '../..') });

(async () => harness(8781, async ({ page, context, base, idle, errors, shot }) => {
  await page.locator('#demoStart').click();
  await page.locator('#consentNo').click();
  await page.waitForFunction(() => window.__pouch3d);
  await idle();
  await page.evaluate(() => localStorage.setItem('sisa.ai', 'true'));
  await page.reload(); await idle();
  await page.locator('[data-step="3"]').click();
  await page.locator('#regenerateImage').click();
  await page.waitForFunction(() => window.__pouch3d?.getState().source === 'image_to_3d');
  await page.getByRole('heading', { name: '3D model from illustration', exact: true }).waitFor();
  let state = await (await context.request.get(base + '/api/state')).json();
  assert.equal(state.image_model.image_id, state.image.image_id);
  assert.equal(state.image_model.source, 'local_image_reconstruction');
  assert.equal(state.image_model.physical_dimensions, false);
  assert.equal(await page.locator('#dimensionsToggle').isDisabled(), true);
  await shot('local-image-pouch-three-quarter', 6);
  await page.locator('[data-view="top"]').click();
  await shot('local-image-pouch-opening', 6);
  await page.locator('[data-view="back"]').click();
  await shot('local-image-pouch-estimated-back', 6);
  await page.locator('[data-view="reset"]').click();
  await page.locator('#pouchScene').focus();
  const before = await page.evaluate(() => window.__pouch3d.getState().yawDeg);
  await page.keyboard.press('ArrowRight');
  assert.notEqual(await page.evaluate(() => window.__pouch3d.getState().yawDeg), before);
  const oldImageId = state.image.image_id;
  await page.locator('#regenerateImage').click();
  await page.waitForFunction(() => document.querySelector('#modelTitle').textContent === '3D model from illustration');
  state = await (await context.request.get(base + '/api/state')).json();
  assert.notEqual(state.image.image_id, oldImageId);
  assert.equal(state.image_model.image_id, state.image.image_id);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#visualModelTab').click();
  await shot('local-image-pouch-mobile', 6);
  assert.equal(await page.locator('#pouchScene canvas').isVisible(), true);
  await page.locator('[data-step="2"]').click();
  await page.locator('[data-available="0"]').click();
  assert.equal(await page.locator('#modelTitle').textContent(), 'SISA pattern model');
  assert.equal(await page.locator('#pouchScene canvas').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS illustration -> local reconstruction -> textured 3D, opening/back/rotation, regenerate, mobile, input invalidation');
}, { imageFixture: fixture }))().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => {
  if (path.resolve(directory).startsWith(path.resolve(os.tmpdir()) + path.sep) && path.basename(directory).startsWith('sisa-image-fixture-')) fs.rmSync(directory, { recursive: true });
});
