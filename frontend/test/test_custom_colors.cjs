const assert = require('node:assert/strict');
const { harness } = require('./browser_helpers.cjs');
const event = (name, data) => `event: ${name}\ndata: ${JSON.stringify(data)}\n\n`;
(async () => harness(8783, async ({ page, context, base, idle, errors, shot }) => {
  await context.addInitScript(() => localStorage.setItem('sisa.ai', 'true'));
  await page.reload(); await idle();
  await page.route('**/api/ai/chat', async route => {
    const state = await (await context.request.get(base+'/api/state')).json();
    const proposal = structuredClone(state.data.request);
    proposal.preferences.front_color = 'ocean mist';
    const result = { status: 'proposal', proposal, reply: 'Kamu ingin warna ocean mist.', understood: [{ field: 'front_color', value: 'ocean mist', from: 'ocean mist' }], assumptions: [], questions: [], trace: { mode: 'live' }, warnings: [{ field: 'front_color', code: 'COLOR_NOT_IN_STOCK', text: 'Warna ocean mist bisa dipakai, tetapi kainnya belum ada di stokmu.', actions: [{ id: 'choose', label: 'Pakai kain biru denim', value: 'blue' }, { id: 'add', label: 'Tambah kain ocean mist', value: 'ocean mist' }, { id: 'ignore', label: 'Abaikan preferensi warna', value: null }] }] };
    await route.fulfill({ contentType: 'text/event-stream', body: event('brief', result)+event('done', { ok: true }) });
  });
  await page.locator('#storyInput').fill('Aku mau depan ocean mist');
  await page.locator('#sendStory').click(); await idle();
  assert.match(await page.locator('#brief').textContent(), /Front color: ocean mist/);
  await shot('free-color-choices', 7);
  await page.getByRole('button', { name: 'Add ocean mist fabric', exact: true }).click();
  await page.getByRole('group', { name: 'Choose the fabric to replace' }).waitFor();
  await page.locator('#colorReplacementChoices button').first().click(); await idle();
  assert.equal(await page.locator('#fabricDialog').isVisible(), true);
  await page.locator('#wizardNext').click();
  await page.locator('#wizardNext').click();
  assert.equal(await page.locator('#fabricColorName').inputValue(), 'ocean mist');
  await page.locator('#fabricColor').fill('#53aec1');
  await page.locator('#fabricName').fill('Kain ocean mist milikku');
  await shot('custom-color-wizard', 7);
  await page.locator('#wizardSave').click(); await idle();
  const state = await (await context.request.get(base+'/api/state')).json();
  assert.equal(state.data.materials.length, 4);
  assert.equal(state.data.materials[0].color, 'ocean mist (#53AEC1)');
  assert.equal(state.data.request.preferences.front_color, 'ocean mist');
  assert.equal(state.data.materials[0].confirmed, false);
  await page.locator('#confirmFabric').click(); await idle();
  await page.waitForFunction(() => window.__pouch3d?.getState().frontHex[0] === '#53AEC1');
  await shot('custom-color-plan', 7);
  await page.locator('[data-step="2"]').click();
  await page.locator('[data-edit="0"]').click();
  await page.locator('#wizardNext').click(); await page.locator('#wizardNext').click();
  assert.equal(await page.locator('#fabricColorName').inputValue(), 'ocean mist');
  assert.equal(await page.locator('#fabricColor').inputValue(), '#53aec1');
  assert.deepEqual(errors, []);
  console.log('PASS free-name request, stock choices, four-slot replacement, named custom hex, current plan color, edit round-trip');
}))().catch(error => { console.error(error); process.exitCode = 1; });
